package com.trackr.app.ui.theme

import androidx.compose.ui.unit.dp

/** Spacing scale. Screen padding is [lg]; tight stacks use [sm] or [md]. */
object TrackrSpace {
    val xxs = 2.dp
    val xs = 4.dp
    val sm = 8.dp
    val md = 12.dp
    val lg = 16.dp
    val xl = 24.dp
    val xxl = 32.dp
}
